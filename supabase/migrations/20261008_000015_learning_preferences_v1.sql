begin;

create table public.learning_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  stage text not null default 'vocabulary',
  revision integer not null default 1,
  stage_provenance jsonb not null default '{"kind":"product_default","ref":"exam-prep-strategy-v1","since":null}'::jsonb,
  stage_reminder jsonb,
  confirmed_at timestamptz,
  updated_by_client_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint learning_preferences_stage_valid check (stage in ('vocabulary', 'mixed', 'exam_practice')),
  constraint learning_preferences_revision_positive check (revision > 0),
  constraint learning_preferences_provenance_object check (jsonb_typeof(stage_provenance) = 'object'),
  constraint learning_preferences_reminder_object check (stage_reminder is null or jsonb_typeof(stage_reminder) = 'object'),
  constraint learning_preferences_client_length check (
    updated_by_client_id is null or char_length(updated_by_client_id) between 1 and 200
  )
);

create table public.learning_preference_revisions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  revision integer not null,
  snapshot jsonb not null,
  change_reason text not null default '',
  created_by_client_id text,
  created_at timestamptz not null default now(),
  constraint learning_preference_revisions_revision_positive check (revision > 0),
  constraint learning_preference_revisions_snapshot_object check (jsonb_typeof(snapshot) = 'object'),
  constraint learning_preference_revisions_reason_length check (char_length(change_reason) <= 1000),
  constraint learning_preference_revisions_client_length check (
    created_by_client_id is null or char_length(created_by_client_id) between 1 and 200
  ),
  unique (user_id, revision)
);

create index learning_preference_revisions_user_revision_idx
  on public.learning_preference_revisions (user_id, revision desc);

create table public.learning_preference_mutation_receipts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id text not null,
  request_id text not null,
  operation text not null,
  request_body jsonb not null,
  response jsonb not null,
  created_at timestamptz not null default now(),
  constraint learning_preference_receipts_client_length check (char_length(client_id) between 1 and 200),
  constraint learning_preference_receipts_request_length check (char_length(request_id) between 8 and 120),
  constraint learning_preference_receipts_operation_valid check (
    operation in ('confirm_stage', 'set_stage_reminder', 'clear_stage_reminder')
  ),
  constraint learning_preference_receipts_request_object check (jsonb_typeof(request_body) = 'object'),
  constraint learning_preference_receipts_response_object check (jsonb_typeof(response) = 'object'),
  unique (user_id, client_id, request_id)
);

create index learning_preference_receipts_user_client_created_idx
  on public.learning_preference_mutation_receipts (user_id, client_id, created_at desc);

