drop policy if exists "plan_mutation_receipts_select_own_client" on public.plan_mutation_receipts;
create policy "plan_mutation_receipts_select_own_client"
  on public.plan_mutation_receipts
  for select
  to authenticated
  using (
    auth.uid() = user_id
    and (
      (auth.jwt() ->> 'client_id') is null
      or (auth.jwt() ->> 'client_id') = client_id
    )
  );

-- OAuth plan writes are allowed only while one of Wenyan's narrow plan RPCs
-- has set the transaction-local marker. Possessing the OAuth token and the
-- capability alone is therefore not enough for direct table mutation.
drop policy if exists "study_plans_insert_oauth_rpc" on public.study_plans;
create policy "study_plans_insert_oauth_rpc"
  on public.study_plans
  for insert
  to authenticated
  with check (
    auth.uid() = user_id
    and current_setting('wenyan.plan_write_rpc', true) = '1'
    and public.wenyan_has_oauth_capability('plans:write')
  );

