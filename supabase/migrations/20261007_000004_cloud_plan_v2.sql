  constraint plan_tasks_title_length check (char_length(title) between 1 and 160),
  constraint plan_tasks_estimated_minutes_valid check (estimated_minutes between 1 and 240),
  constraint plan_tasks_reason_length check (char_length(reason) <= 1000),
  constraint plan_tasks_config_object check (jsonb_typeof(config) = 'object'),
  constraint plan_tasks_state_valid check (state in ('active', 'cancelled')),
  unique (plan_id, position)
);

create index if not exists plan_tasks_user_due_idx
  on public.plan_tasks (user_id, due_date, position);

