    foreign key (plan_id, user_id)
    references public.study_plans(id, user_id)
    on delete cascade,
  constraint plan_tasks_position_nonnegative check (position >= 0),
  constraint plan_tasks_kind_valid check (
    kind in ('chapter', 'smart_review', 'word_set', 'dictation', 'weak_words', 'mixed_session')
