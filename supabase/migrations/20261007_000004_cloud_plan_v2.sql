create table if not exists public.study_plans (
  id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  timezone text not null default 'Asia/Shanghai',
  status text not null default 'active',
  revision integer not null default 1,
  source text not null default 'wenyan-english',
  created_by_client_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint study_plans_title_length check (char_length(title) between 1 and 160),
  constraint study_plans_timezone_length check (char_length(timezone) between 1 and 64),
  constraint study_plans_status_valid check (status in ('active', 'archived')),
  constraint study_plans_revision_positive check (revision > 0),
  constraint study_plans_source_length check (char_length(source) between 1 and 64),
  unique (id, user_id)
);

create index if not exists study_plans_user_status_updated_idx
  on public.study_plans (user_id, status, updated_at desc);

create table if not exists public.plan_tasks (
  id uuid primary key,
  plan_id uuid not null,
